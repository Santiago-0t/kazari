//! Terminal emulators: color scheme, font and window effect (transparency or acrylic).

use serde_json::{Value, json};

use crate::palette::Palette;
use crate::rice::{Rice, Terminal, WindowEffect};
use crate::text::{EditError, object_at, parse_jsonc};

const ANSI_NAMES: [&str; 8] = [
    "black", "red", "green", "yellow", "blue", "purple", "cyan", "white",
];

fn scheme_name(palette: &Palette) -> String {
    format!("kazari {}", palette.name)
}

/// Updates Windows Terminal's `settings.json`: adds (or replaces) the kazari color scheme and
/// sets it, the font and the window effect as defaults for every profile.
pub fn patch_windows_terminal(existing: &str, rice: &Rice) -> Result<String, EditError> {
    let mut settings = parse_jsonc(existing)?;
    let palette = &rice.palette;
    let name = scheme_name(palette);

    let mut scheme = json!({
        "name": name,
        "background": palette.background.to_hex(),
        "foreground": palette.foreground.to_hex(),
        "cursorColor": palette.accent.to_hex(),
        "selectionBackground": palette.surface.to_hex(),
    });
    for (i, color_name) in ANSI_NAMES.iter().enumerate() {
        scheme[*color_name] = json!(palette.ansi[i].to_hex());
        let bright = format!("bright{}{}", color_name[..1].to_uppercase(), &color_name[1..]);
        scheme[bright] = json!(palette.ansi[i + 8].to_hex());
    }

    let root = settings.as_object_mut().expect("parse_jsonc returns an object");
    let schemes = root.entry("schemes").or_insert_with(|| json!([]));
    if !schemes.is_array() {
        *schemes = json!([]);
    }
    let schemes = schemes.as_array_mut().expect("just ensured an array");
    schemes.retain(|s| s.get("name").and_then(Value::as_str) != Some(name.as_str()));
    schemes.push(scheme);

    let effect = rice.effect.for_terminal(Terminal::WindowsTerminal);
    let root = settings.as_object_mut().expect("parse_jsonc returns an object");
    let defaults = object_at(object_at(root, "profiles"), "defaults");
    defaults.insert("colorScheme".into(), json!(name));
    defaults.insert(
        "font".into(),
        json!({ "face": rice.font, "size": rice.font_size }),
    );
    defaults.insert("opacity".into(), json!((effect.opacity() * 100.0).round() as u8));
    defaults.insert(
        "useAcrylic".into(),
        json!(matches!(effect, WindowEffect::Acrylic { .. })),
    );

    Ok(serde_json::to_string_pretty(&settings)? + "\n")
}

/// A Lua module for WezTerm. Load it from `wezterm.lua` with
/// `require("kazari").apply(config)`.
pub fn wezterm_module(rice: &Rice) -> String {
    let p = &rice.palette;
    let list = |colors: &[crate::palette::Color]| {
        colors
            .iter()
            .map(|c| format!("\"{c}\""))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let effect = rice.effect.for_terminal(Terminal::WezTerm);
    let backdrop = match effect {
        WindowEffect::Acrylic { .. } => "Acrylic",
        _ => "Auto",
    };
    format!(
        r#"-- Generated by kazari. Edits are overwritten on the next apply.
local wezterm = require("wezterm")
local M = {{}}

function M.apply(config)
  config.colors = {{
    background = "{bg}",
    foreground = "{fg}",
    cursor_bg = "{accent}",
    selection_bg = "{surface}",
    ansi = {{ {ansi} }},
    brights = {{ {brights} }},
  }}
  config.font = wezterm.font("{font}")
  config.font_size = {size}
  config.window_background_opacity = {opacity:.2}
  config.win32_system_backdrop = "{backdrop}"
  return config
end

return M
"#,
        bg = p.background,
        fg = p.foreground,
        accent = p.accent,
        surface = p.surface,
        ansi = list(&p.ansi[..8]),
        brights = list(&p.ansi[8..]),
        font = rice.font,
        size = rice.font_size,
        opacity = effect.opacity(),
    )
}

/// A TOML file for Alacritty. Import it from `alacritty.toml` with
/// `[general] import = ["kazari.toml"]`. Alacritty has no acrylic, so it only gets opacity.
pub fn alacritty_import(rice: &Rice) -> String {
    let p = &rice.palette;
    let section = |offset: usize| {
        ANSI_NAMES
            .iter()
            .enumerate()
            .map(|(i, name)| {
                let name = if *name == "purple" { "magenta" } else { name };
                format!("{name} = \"{}\"", p.ansi[i + offset])
            })
            .collect::<Vec<_>>()
            .join("\n")
    };
    let effect = rice.effect.for_terminal(Terminal::Alacritty);
    format!(
        "# Generated by kazari. Edits are overwritten on the next apply.\n\n[window]\nopacity = {opacity:.2}\n\n[font]\nnormal = {{ family = \"{font}\" }}\nsize = {size}\n\n[colors.primary]\nbackground = \"{bg}\"\nforeground = \"{fg}\"\n\n[colors.normal]\n{normal}\n\n[colors.bright]\n{bright}\n",
        opacity = effect.opacity(),
        font = rice.font,
        size = rice.font_size,
        bg = p.background,
        fg = p.foreground,
        normal = section(0),
        bright = section(8),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_support::sample_rice;

    #[test]
    fn windows_terminal_gets_scheme_font_and_acrylic() {
        let existing = r##"{
            // user comment
            "defaultProfile": "{abc}",
            "profiles": { "defaults": { "padding": "8" }, "list": [] },
            "schemes": [ { "name": "kazari Zenwritten", "background": "#000000" } ]
        }"##;
        let mut rice = sample_rice();
        rice.effect = WindowEffect::Acrylic { opacity: 80 };
        let out: Value = serde_json::from_str(&patch_windows_terminal(existing, &rice).unwrap()).unwrap();

        assert_eq!(out["defaultProfile"], "{abc}");
        assert_eq!(out["profiles"]["defaults"]["padding"], "8");
        assert_eq!(out["profiles"]["defaults"]["colorScheme"], "kazari Zenwritten");
        assert_eq!(out["profiles"]["defaults"]["opacity"], 80);
        assert_eq!(out["profiles"]["defaults"]["useAcrylic"], true);
        assert_eq!(
            out["profiles"]["defaults"]["font"]["face"],
            "JetBrainsMono Nerd Font"
        );

        let schemes = out["schemes"].as_array().unwrap();
        assert_eq!(
            schemes.len(),
            1,
            "the old kazari scheme is replaced, not duplicated"
        );
        assert_eq!(schemes[0]["background"], "#191919");
        assert_eq!(schemes[0]["brightBlack"], "#3d3839");
    }

    #[test]
    fn transparency_only_disables_acrylic() {
        let mut rice = sample_rice();
        rice.effect = WindowEffect::Transparent { opacity: 90 };
        let out: Value = serde_json::from_str(&patch_windows_terminal("", &rice).unwrap()).unwrap();
        assert_eq!(out["profiles"]["defaults"]["useAcrylic"], false);
        assert_eq!(out["profiles"]["defaults"]["opacity"], 90);
    }

    #[test]
    fn wezterm_uses_the_acrylic_backdrop() {
        let mut rice = sample_rice();
        rice.effect = WindowEffect::Acrylic { opacity: 75 };
        let lua = wezterm_module(&rice);
        assert!(lua.contains("win32_system_backdrop = \"Acrylic\""));
        assert!(lua.contains("window_background_opacity = 0.75"));
    }

    #[test]
    fn alacritty_degrades_acrylic_to_opacity() {
        let mut rice = sample_rice();
        rice.effect = WindowEffect::Acrylic { opacity: 70 };
        let toml = alacritty_import(&rice);
        assert!(toml.contains("opacity = 0.70"));
        assert!(toml.contains("magenta = \"#b279a7\""));
    }
}
